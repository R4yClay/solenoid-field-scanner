def set_Standard_Doc_Formatting(doc):
    """Настройка полей А4 (слева 30 мм, справа 10 мм, сверху и снизу 20 мм) и шрифта Times New Roman 14 pt, 1,5 интервал."""
    for section in doc.sections:
        section.page_width = Mm(210)
        section.page_height = Mm(297)
        section.left_margin = Mm(30)
        section.right_margin = Mm(10)
        section.top_margin = Mm(20)
        section.bottom_margin = Mm(20)

    style = doc.styles['Normal']
    font = style.font
    font.name = 'Times New Roman'
    font.size = Pt(14)
    font.color.rgb = RGBColor(0, 0, 0)
    style.element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')

    pf = style.paragraph_format
    pf.line_spacing = 1.5
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.first_line_indent = Mm(12.5)
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def add_p(doc, text, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
          indent_mm=12.5, space_before=0, space_after=0, font_size=14, color=None):
    p = doc.add_paragraph()
    p.paragraph_format.alignment = align
    p.paragraph_format.first_line_indent = Mm(indent_mm)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.name = 'Times New Roman'
    run.font.size = Pt(font_size)
    if color is not None:
        run.font.color.rgb = color
    run.element.rPr.rFonts.set(qn('w:eastAsia'), 'Times New Roman')
    return p


def add_heading_custom(doc, text, level=1, blue_style=True):
    """Заголовок в стиле образца ГБУ ДО Центр «Интеллект» (выравнивание слева, сине-голубой цвет, полужирный)."""
    p = doc.add_paragraph()
    p.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p.paragraph_format.first_line_indent = Mm(0)
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = Pt(12 if level == 1 else 8)
    p.paragraph_format.space_after = Pt(6)
    run = p.add_run(text)
